function day(program, type, n, name, sets, desc, note) {
  return {
    id: `${program}${n}`,
    type,
    program,
    day: n,
    title: name,
    struct: sets,
    exercises: [{ name, sets, desc }],
    note,
  }
}

const tc = (n, name, sets, desc, note) => day('tc', 'TC', n, name, sets, desc, note)
const ac = (n, name, sets, desc, note) => day('ac', 'BW', n, name, sets, desc, note)

